#!/usr/bin/env node
/**
 * Writes src/lib/generated/blog-article-slugs.ts: the folder-based blog article
 * routes under src/app/blog (a folder with page.tsx, excluding "[slug]" and "page").
 *
 * Why: the sitemap and llms.txt list these routes. Reading src/app/blog at runtime
 * works during `next build`, but the sitemap is rebuilt on the server whenever prices
 * are saved in the admin (revalidatePath), and the deployed server has no src folder,
 * so 23 articles silently dropped out of the sitemap. The list is now fixed at build
 * time. Runs automatically before `npm run build` (prebuild); a test checks the
 * committed file matches the folders.
 */
import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const base = path.join(root, "src", "app", "blog");

export function listBlogArticleFolders() {
  return readdirSync(base, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .filter((slug) => slug !== "[slug]" && slug !== "page" && existsSync(path.join(base, slug, "page.tsx")))
    .sort();
}

export function renderManifest(slugs) {
  return `// GENERATED by scripts/generate-blog-slugs.mjs (runs before \`npm run build\`). Do not edit by hand.\nexport const BLOG_ARTICLE_FOLDER_SLUGS: readonly string[] = ${JSON.stringify(slugs, null, 2)};\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = path.join(root, "src", "lib", "generated", "blog-article-slugs.ts");
  mkdirSync(path.dirname(out), { recursive: true });
  writeFileSync(out, renderManifest(listBlogArticleFolders()));
  console.log(`blog article slugs: ${listBlogArticleFolders().length} written to ${path.relative(root, out)}`);
}
